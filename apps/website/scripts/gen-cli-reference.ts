// src/content/docs/docs/reference/cli.md from the binary's own --help output.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { RDOCK, SITE } from './lib.ts';

const help = (args: string[]) => execFileSync(RDOCK, [...args, '--help'], { encoding: 'utf8' }).trimEnd();
const top = help([]);
const commands = [...top.matchAll(/^ {2}([a-z][a-z-]*) {2,}/gm)].map((m) => m[1]).filter((c) => c !== 'help');

const sections = commands.map((command) => `## \`rdock ${command}\`\n\n\`\`\`text\n${help([command])}\n\`\`\``);
const page = `---
title: CLI
description: Every rdock command and flag, generated from the binary's --help output.
sidebar:
  order: 2
---

{/* Generated by scripts/gen-cli-reference.ts from \`rdock --help\`. Do not edit by hand. */}

Exit codes: \`0\` success, \`1\` the command ran and found problems (for example \`validate\` reported errors), \`2\` the command could not run (bad arguments, unreadable files, the admin API unreachable).

\`\`\`text
${top}
\`\`\`

${sections.join('\n\n')}
`;
writeFileSync(join(SITE, 'src/content/docs/docs/reference/cli.mdx'), page);
console.log(`cli reference: ${commands.length} commands`);
