// From the maturity and deprecation registries in schema/rdock.v1.json (`x-rdock-features`,
// `x-rdock-deprecations`, generated from crates/rdock-model, ADR-0033):
//   src/data/maturity.json                                the levels, for <Status feature="…" />
//   src/content/docs/docs/project/maturity.mdx            every feature with its level
//   src/content/docs/docs/project/deprecations.mdx        every deprecated element
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, SITE } from './lib.ts';

interface Feature {
  id: string;
  level: 'stable' | 'beta' | 'experimental';
  since: string;
  summary: string;
  cargo_feature?: string;
  locations: string[];
}
interface Deprecation {
  kind: string;
  element: string;
  since: string;
  removal: string;
  replacement: string;
  note: string;
  automatic: boolean;
}

const schema = JSON.parse(readFileSync(join(ROOT, 'schema/rdock.v1.json'), 'utf8'));
const features: Feature[] = schema['x-rdock-features'];
const deprecations: Deprecation[] = schema['x-rdock-deprecations'];
if (!Array.isArray(features) || !Array.isArray(deprecations)) throw new Error('schema/rdock.v1.json has no registries; run `just schema`');

writeFileSync(
  join(SITE, 'src/data/maturity.json'),
  `${JSON.stringify({ features: features.map(({ id, level, since, summary }) => ({ id, level, since, summary })) }, null, 2)}\n`,
);

/** Table cells: pipes escaped, braces and angle brackets outside code escaped for MDX. */
const cell = (text: string) =>
  text
    .split(/(`+[^`]*`+)/)
    .map((part, i) => (i % 2 === 1 ? part : part.replace(/[{}<>]/g, (c) => `\\${c}`)))
    .join('')
    .replaceAll('|', '\\|')
    .replace(/\n/g, ' ');
const where = (f: Feature) =>
  f.locations.length === 0 ? 'outside the configuration file' : f.locations.map((l) => `\`${l.replace('*', '<name>')}\``).join(', ');

function table(level: Feature['level']): string {
  const rows = features.filter((f) => f.level === level);
  const optIn = level === 'experimental';
  const head = optIn
    ? '| Feature | Since | Opt-in name | Build | Configuration |\n|---|---|---|---|---|'
    : '| Feature | Since | Configuration |\n|---|---|---|';
  const lines = rows.map((f) =>
    optIn
      ? `| ${cell(f.summary)} | ${f.since} | \`${f.id}\` | ${f.cargo_feature ? `\`--features ${f.cargo_feature}\`` : 'every build'} | ${cell(where(f))} |`
      : `| ${cell(f.summary)} (\`${f.id}\`) | ${f.since} | ${cell(where(f))} |`,
  );
  return [head, ...lines].join('\n');
}

const generated = (source: string) => `{/* Generated by scripts/gen-stability.ts from ${source}. Do not edit by hand. */}`;

writeFileSync(
  join(SITE, 'src/content/docs/docs/project/maturity.mdx'),
  `---
title: Maturity levels
description: Every ReverseDock feature with its maturity level (stable, beta or experimental), generated from the registry in the binary.
sidebar:
  order: 7
---

import Status from '../../../../components/Status.astro';

${generated('the maturity registry in schema/rdock.v1.json')}

Every feature has one of three levels, set in one registry in the code that also feeds \`rdock validate\`, \`rdock version\`, the JSON Schema (\`x-rdock-maturity\`) and the badges in this documentation ([ADR-0033](https://github.com/Docker-Hunterpedia/ReverseDock/blob/main/docs/decisions/0033-v1-0-stable.md)). What each level promises is on [Stability and support](/docs/project/stability/).

- <Status maturity="stable" /> covered by the stability promise: it breaks only in a major release, after a deprecation.
- <Status maturity="beta" /> not removed without a deprecation; details may change in a minor release, with a migration note.
- <Status maturity="experimental" /> no promise: may change or be removed in any release. A configuration that uses one must name it in the top-level \`experimental\` list, or it is refused:

\`\`\`yaml title="rdock.yaml (excerpt)"
experimental: [wasm]
\`\`\`

At load and at every reload, ReverseDock logs one warning per experimental feature in use and one info line per beta feature, and sets \`rdock_experimental_feature_in_use{feature}\`. \`GET /api/v1/status\` lists both under \`features_in_use\`, and the dashboard's overview shows them.

A setting that is not listed below belongs to the feature that lists its nearest parent: \`listeners.<name>.http3.enabled\` is part of \`listeners.<name>.http3\`.

## Experimental

${table('experimental')}

## Beta

${table('beta')}

## Stable

${table('stable')}

TLS and the HTTP cache run on parts of Pingora that Pingora itself calls experimental (its rustls backend and its cache integration). ReverseDock offers them at the levels above and carries upstream changes itself.
`,
);

const rows = deprecations.map(
  (d) => `| \`${d.element}\` (${d.kind.replaceAll('_', ' ')}) | ${d.since} | ${d.removal} | ${cell(d.replacement)} | ${d.automatic ? 'yes' : 'no'} |`,
);
const notes = deprecations.map((d) => `- **\`${d.element}\`**: ${cell(d.note)}`);
writeFileSync(
  join(SITE, 'src/content/docs/docs/project/deprecations.mdx'),
  `---
title: Deprecations
description: Every deprecated ReverseDock setting, label, flag, API operation and metric, with the release that removes it and its replacement.
sidebar:
  order: 8
---

${generated('the deprecation registry in schema/rdock.v1.json')}

A deprecated element keeps working until the release in the "Removal" column, which is always a major release ([Stability and support](/docs/project/stability/)). While it is in use, \`rdock validate\` warns (\`--strict\` and \`--deprecations error\` fail; \`--format json\` carries \`code: deprecated\`, \`element\`, \`since\`, \`removal\` and \`replacement\`), ReverseDock logs one warning per element at each load and sets \`rdock_deprecated_config_in_use{element}\`, \`GET /api/v1/status\` lists it under \`deprecations_in_use\`, and the dashboard's overview shows it. Deprecated keys carry \`"deprecated": true\` in the JSON Schema, deprecated API operations in the OpenAPI document, and their answers carry the \`Deprecation\` (RFC 9745) and \`Sunset\` (RFC 8594) headers. A deprecated CLI flag prints a warning on standard error.

\`rdock migrate config rdock.yaml\` rewrites every element marked "automatic" to its replacement: it prints the result, \`--diff\` prints a diff and \`--write\` replaces the file after copying it to \`rdock.yaml.bak\`. It keeps comments and formatting where the change can be made as a text edit; see [Move off deprecated settings](/docs/project/stability/#move-off-deprecated-settings).

${deprecations.length === 0 ? 'None: nothing is deprecated in this release.' : `| Element | Deprecated in | Removal | Replacement | Automatic |\n|---|---|---|---|---|\n${rows.join('\n')}\n\n## Notes\n\n${notes.join('\n')}`}
`,
);
console.log(`stability: ${features.length} features, ${deprecations.length} deprecations`);
