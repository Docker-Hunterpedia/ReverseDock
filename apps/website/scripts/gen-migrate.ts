// The migration reference pages (ADR-0033), from files the code generates:
//   src/content/docs/docs/reference/traefik-subset.mdx   from tests/conformance/traefik-labels/coverage.json
//                                                         (crates/providers/rdock-provider-docker/src/labels/coverage.rs)
//   src/content/docs/docs/reference/migrate-report.mdx   from schema/migrate-report.v1.json (`x-rdock-codes`,
//                                                         crates/rdock-migrate/src/report.rs)
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, SITE } from './lib.ts';

interface Row {
  key: string;
  status: 'exact' | 'approximate' | 'manual' | 'none';
  rdock: string;
  note: string;
  fixtures: string[];
  proven_by?: string;
}
interface Code {
  id: string;
  level: 'exact' | 'approximate' | 'manual' | 'dropped';
  summary: string;
  help: string;
}

/** Table cells: pipes escaped, braces and angle brackets outside code escaped for MDX. */
const cell = (text: string) =>
  text
    .split(/(`+[^`]*`+)/)
    .map((part, i) => (i % 2 === 1 ? part : part.replace(/[{}<>]/g, (c) => `\\${c}`)))
    .join('')
    .replaceAll('|', '\\|')
    .replace(/\n/g, ' ');
const generated = (source: string) => `{/* Generated by scripts/gen-migrate.ts from ${source}. Do not edit by hand. */}`;
const SUITE = 'https://github.com/Docker-Hunterpedia/ReverseDock/tree/main/tests/conformance/traefik-labels';

const coverage = JSON.parse(readFileSync(join(ROOT, 'tests/conformance/traefik-labels/coverage.json'), 'utf8'));
const rows: Row[] = coverage.options;
const traefik = coverage.traefik as { version: string; reference: string; checked: string };
const totals = coverage.totals as Record<string, number>;
const supported = (totals.exact ?? 0) + (totals.approximate ?? 0);

const groups: [string, (r: Row) => boolean][] = [
  ['Provider labels', (r) => !/^traefik\.(http|tcp|udp)\./.test(r.key)],
  ['HTTP routers', (r) => r.key.startsWith('traefik.http.routers.')],
  ['HTTP services', (r) => r.key.startsWith('traefik.http.services.')],
  ['HTTP middlewares', (r) => r.key.startsWith('traefik.http.middlewares.')],
  ['TCP', (r) => r.key.startsWith('traefik.tcp.')],
  ['UDP', (r) => r.key.startsWith('traefik.udp.')],
];
const label = { exact: 'exact', approximate: 'approximate', manual: 'manual', none: 'none' } as const;
const proof = (r: Row) => {
  if (r.proven_by) return cell(r.proven_by);
  const links = r.fixtures.slice(0, 3).map((f) => `[${f.replace(/\.yaml$/, '')}](${SUITE}/${f})`);
  const more = r.fixtures.length - links.length;
  return more > 0 ? `${links.join(', ')} and ${more} more` : links.join(', ');
};
const section = ([title, test]: [string, (r: Row) => boolean]) => {
  const lines = rows
    .filter(test)
    .map((r) => `| \`${r.key}\` | ${label[r.status]} | ${cell(r.status === 'approximate' ? `${r.rdock}. ${r.note}` : r.rdock || r.note)} | ${proof(r)} |`);
  return `## ${title}\n\n| Traefik label | Status | ReverseDock | Proven by |\n|---|---|---|---|\n${lines.join('\n')}`;
};

writeFileSync(
  join(SITE, 'src/content/docs/docs/reference/traefik-subset.mdx'),
  `---
title: Supported Traefik subset
description: Every Traefik ${traefik.version} Docker label with what ReverseDock does with it (exact, approximate, manual or none) and the conformance fixture that proves it, generated from the coverage table.
sidebar:
  order: 4
---

${generated('tests/conformance/traefik-labels/coverage.json')}

Pinned to **Traefik ${traefik.version}** ([Docker label reference](${traefik.reference}), checked ${traefik.checked}). Of ${rows.length} labels, **${supported} are translated**: ${totals.exact ?? 0} exact and ${totals.approximate ?? 0} approximate (with the difference stated); ${totals.manual ?? 0} need a setting outside labels (manual) and ${totals.none ?? 0} have no equivalent. The Docker provider and \`rdock migrate traefik\` read labels through the same translator, so this table says what both do.

- **exact**: the same behaviour.
- **approximate**: translated; the difference is stated in the row.
- **manual**: not translated from labels; the row says what to set in rdock.yaml instead. \`rdock migrate traefik\` reports it as \`manual\`.
- **none**: no equivalent; the label is reported in the logs, \`rdock status\` and the migration report, and ignored.

"Proven by" names the fixtures of the [conformance suite](${SUITE}) that use the label; a test fails when a row has none, when the translator takes a label marked manual or none (or refuses one marked exact or approximate), or when a fixture uses a label that is not in the table. The exact rows are also what the [differential test](https://github.com/Docker-Hunterpedia/ReverseDock/tree/main/tests/conformance/traefik-diff) compares against a running Traefik. The [stability promise](/docs/project/stability/) covers the labels marked exact and approximate.

${groups.map(section).join('\n\n')}
`,
);

const schema = JSON.parse(readFileSync(join(ROOT, 'schema/migrate-report.v1.json'), 'utf8'));
const codes: Code[] = schema['x-rdock-codes'];
if (!Array.isArray(codes)) throw new Error('schema/migrate-report.v1.json has no x-rdock-codes; run `just schema`');
const codeRows = codes
  .slice()
  .sort((a, b) => a.id.localeCompare(b.id))
  .map((c) => `| \`${c.id}\` | ${c.level} | ${cell(c.summary)} | ${cell(c.help)} |`);
writeFileSync(
  join(SITE, 'src/content/docs/docs/reference/migrate-report.mdx'),
  `---
title: Migration report
description: The report of rdock migrate traefik, caddy and nginx, its four levels, the JSON format (schema/migrate-report.v1.json) and every finding code, generated from the code list.
sidebar:
  order: 9
---

import Status from '../../../../components/Status.astro';

${generated('schema/migrate-report.v1.json')}

<Status maturity="beta" /> \`rdock migrate traefik\`, \`rdock migrate caddy\` and \`rdock migrate nginx\` account for **every source item** (a label, a key of a configuration file or a JSON pointer, a flag, an environment variable, an NGINX directive) **exactly once**, at one of four levels. Each finding has a stable code, the source location, the generated object's path in rdock.yaml when there is one, a message and a hint. A test fails when an item has no finding or two. Findings about the written result as a whole (a validation error of a fragment, labels left to the Docker provider, a route written disabled, a default of the other proxy written explicitly or changed) have no source item and are counted apart.

| Level | Meaning | In the output |
|---|---|---|
| \`exact\` | The same behaviour | written |
| \`approximate\` | Works, with a stated difference | written; listed at the top of the output |
| \`manual\` | Needs a decision | left out, or the route is written \`enabled: false\` so it never goes live without (say) its authentication; the finding says what to do |
| \`dropped\` | No equivalent | left out; the finding says why |

Output:

- **Text** on standard error: the counts first, then the findings grouped by level (manual, dropped, approximate). The YAML on standard output starts with the same counts and every finding that is not exact as comments.
- **\`--report FILE\`**: the report as JSON, described by [\`schema/migrate-report.v1.json\`](https://github.com/Docker-Hunterpedia/ReverseDock/blob/main/schema/migrate-report.v1.json) (\`rdock schema --migrate-report\` prints it). \`--report -\` writes it to standard error instead of the text.
- **\`--strict\`**: exit \`2\` when any finding is \`manual\` or \`dropped\`.

Exit codes: \`0\` migrated (findings may exist), \`1\` the input is not one the command reads (a Compose file or a Traefik configuration; Caddy's JSON, so a Caddyfile is refused with how to adapt it; an NGINX configuration), \`2\` an error (an unreadable file) or, with \`--strict\`, something to review. The same codes as \`rdock migrate config\` (where \`2\` is an I/O error).

The JSON format and the codes are beta: fields and codes may be added in a minor release, and a change to an existing one comes with a migration note.

## Finding codes

| Code | Level | Meaning | What to do |
|---|---|---|---|
${codeRows.join('\n')}
`,
);
console.log(`migrate references: ${rows.length} Traefik labels, ${codes.length} finding codes`);
