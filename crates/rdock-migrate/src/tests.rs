const COMPOSE: &str = r#"
services:
  whoami:
    image: traefik/whoami
    labels:
      - traefik.enable=true
      - traefik.http.routers.whoami.rule=Host(`whoami.example.com`)
      - traefik.http.routers.whoami.entrypoints=websecure
      - traefik.http.routers.whoami.tls.certresolver=le
      - traefik.http.routers.whoami.middlewares=strip
      - traefik.http.middlewares.strip.stripprefix.prefixes=/who
  api:
    image: example/api
    expose: ["8080", "9100"]
    labels:
      traefik.enable: "true"
      traefik.http.routers.api.rule: Host(`api.example.com`)
      traefik.http.services.api.loadbalancer.server.port: 8080
      traefik.http.middlewares.p.plugin.demo.key: v
  db:
    image: postgres
    labels:
      traefik.http.routers.db.rule: Host(`db.example.com`)
"#;

fn options() -> Options {
    Options {
        file: "compose.yaml".to_owned(),
        ..Options::default()
    }
}

fn run(text: &str) -> Migration {
    traefik(text, &options()).unwrap()
}

/// The finding of the item named `item`.
fn finding<'m>(m: &'m Migration, item: &str) -> &'m report::Finding {
    m.report
        .findings
        .iter()
        .find(|f| f.source.as_ref().is_some_and(|s| s.item == item))
        .unwrap_or_else(|| panic!("no finding for {item}: {:#?}", m.report.findings))
}

#[test]
fn compose_labels_become_routes_with_service_names_as_hosts() {
    let m = run(COMPOSE);
    assert_eq!(m.input, Input::Compose);
    assert!(m.yaml.contains("Host(`whoami.example.com`)"), "{}", m.yaml);
    // The service name is the backend's host; without a port, 80 is assumed and reported.
    assert!(m.yaml.contains("address: api:8080"), "{}", m.yaml);
    assert!(m.yaml.contains("address: whoami:80"), "{}", m.yaml);
    assert_eq!(
        finding(&m, "services.whoami").code,
        "compose.service.port_assumed"
    );
    assert_eq!(
        finding(&m, "traefik.http.middlewares.p.plugin.demo.key").level,
        Level::Dropped
    );
    assert_eq!(
        finding(&m, "traefik.http.routers.db.rule").code,
        "traefik.label.not_exposed"
    );
    assert_eq!(
        finding(&m, "services.db").code,
        "compose.service.not_exposed"
    );
    assert_eq!(
        finding(&m, "traefik.http.routers.whoami.tls.certresolver").level,
        Level::Approximate
    );
    assert_eq!(
        finding(&m, "traefik.http.middlewares.strip.stripprefix.prefixes").code,
        "traefik.label.exact"
    );
    assert!(m.yaml.starts_with("# Generated by `rdock migrate traefik`"));
    // Defaults are left out.
    assert!(!m.yaml.contains("enabled: true"), "{}", m.yaml);
    assert!(!m.yaml.contains("priority: 0"), "{}", m.yaml);
}

/// The accounting invariant (ADR-0033): every `traefik.*`/`rdock.*` label and every service
/// with labels has exactly one finding; nothing vanishes.
#[test]
fn every_label_is_accounted_for_once() {
    let m = run(COMPOSE);
    let labels = COMPOSE
        .lines()
        .filter(|l| l.contains("traefik.") && !l.contains("image:"))
        .count();
    let services = 3;
    assert_eq!(m.report.summary.items, labels + services, "{:#?}", m.report);
    let s = &m.report.summary;
    assert_eq!(s.exact + s.approximate + s.manual + s.dropped, s.items);
    let mut seen = std::collections::BTreeSet::new();
    for f in m.report.findings.iter().filter(|f| f.source.is_some()) {
        let source = f.source.clone().unwrap();
        assert!(seen.insert((source.scope, source.item)), "accounted twice");
    }
}

#[test]
fn the_builder_refuses_a_missing_or_double_finding() {
    let mut b = report::Builder::default();
    let source = report::Source {
        file: "f".into(),
        line: None,
        scope: None,
        kind: report::ItemKind::Label,
        item: "a".into(),
    };
    let id = b.item(source.clone());
    let _ = b.item(report::Source {
        item: "b".into(),
        ..source.clone()
    });
    b.account(id, report::Finding::new("traefik.label.exact", "x"));
    b.account(id, report::Finding::new("traefik.label.exact", "x"));
    let info = report::SourceInfo {
        kind: "traefik".into(),
        checked_against: "Traefik v3.7".into(),
        files: vec![],
    };
    let err = b.finish("t", info).unwrap_err();
    assert!(err.0.contains("not accounted for: [f: label b]"), "{err}");
    assert!(err.0.contains("accounted for twice: [f: label a]"), "{err}");
}

#[test]
fn every_code_used_is_listed_with_its_level() {
    let m = run(COMPOSE);
    for f in &m.report.findings {
        let code = report::code_info(&f.code).unwrap_or_else(|| panic!("{} is not listed", f.code));
        assert_eq!(code.level, f.level, "{}", f.code);
    }
    let mut ids: Vec<&str> = report::CODES.iter().map(|c| c.id).collect();
    let n = ids.len();
    ids.sort_unstable();
    ids.dedup();
    assert_eq!(ids.len(), n, "a code is listed twice");
}

