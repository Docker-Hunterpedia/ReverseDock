#[test]
fn gap1_compose_interpolation_with_env_files() {
    let compose = "services:\n  web:\n    image: x\n    expose: [80]\n    labels:\n      traefik.enable: 'true'\n      traefik.http.routers.web.rule: Host(`${DOMAIN}`) || Host(`www.${DOMAIN:-example.org}`)\n";
    // Without the variable: Compose's empty string, reported as manual.
    let m = run(compose);
    let f = finding(&m, "traefik.http.routers.web.rule");
    assert_eq!(f.code, "compose.interpolation.unset");
    assert!(f.hint.as_deref().unwrap().contains("--env-file"));
    // With it: translated.
    let vars = compose::env_file("DOMAIN=example.com\n", &compose::Vars::new()).unwrap();
    let m = traefik(compose, &Options { vars, ..options() }).unwrap();
    assert!(
        m.yaml
            .contains("Host(`example.com`) || Host(`www.example.com`)"),
        "{}",
        m.yaml
    );
    // Translated (the router names no entry point, which is its only difference).
    assert_eq!(
        finding(&m, "traefik.http.routers.web.rule").code,
        "traefik.router.all_entrypoints"
    );
    // A required variable.
    let m = run(
        "services:\n  web:\n    image: x\n    labels:\n      traefik.enable: 'true'\n      traefik.http.routers.web.rule: Host(`${DOMAIN:?set DOMAIN}`)\n",
    );
    assert_eq!(
        finding(&m, "traefik.http.routers.web.rule").code,
        "compose.interpolation.required"
    );
}

