#[test]
fn static_flags_of_the_traefik_service_are_read_and_credentials_never_copied() {
    let compose = r"
services:
  traefik:
    image: traefik:v3.7
    command:
      - --entrypoints.web.address=:80
      - --entrypoints.web.http.redirections.entrypoint.to=websecure
      - --entrypoints.websecure.address=:443
      - --entrypoints.websecure.http.tls.certresolver=le
      - --providers.docker=true
      - --providers.docker.network=proxy
      - --certificatesresolvers.le.acme.email=ops@example.com
      - --certificatesresolvers.le.acme.storage=/letsencrypt/acme.json
      - --certificatesresolvers.le.acme.dnschallenge.provider=cloudflare
      - --certificatesresolvers.le.acme.eab.hmacencoded=c2VjcmV0LWhtYWMta2V5
      - --api.insecure=true
    environment:
      CF_DNS_API_TOKEN: super-secret-token-value
      TRAEFIK_LOG_LEVEL: DEBUG
  app:
    image: traefik/whoami
    labels:
      traefik.http.routers.app.rule: Host(`app.example.com`)
      traefik.http.routers.app.entrypoints: websecure
";
    let m = traefik(
        compose,
        &Options {
            full: true,
            ..options()
        },
    )
    .unwrap();
    for secret in ["super-secret-token-value", "c2VjcmV0LWhtYWMta2V5"] {
        assert!(!m.yaml.contains(secret), "{}", m.yaml);
        let json = serde_json::to_string(&m.report).unwrap();
        assert!(!json.contains(secret), "{json}");
    }
    for want in [
        "address: \":80\"",
        "address: \":443\"",
        "email: ops@example.com",
        "${env:CF_DNS_API_TOKEN}",
        "expose_by_default: true",
        "network: proxy",
        "redirect_http_to_https: true",
    ] {
        assert!(m.yaml.contains(want), "{want}:\n{}", m.yaml);
    }
    // exposedByDefault is Traefik's default: written explicitly, a security-relevant choice;
    // so the app without `traefik.enable` is routed (its labels are live, not written).
    let docker = finding(&m, "--providers.docker");
    assert_eq!(docker.code, "traefik.static.expose_by_default");
    assert!(docker.security);
    assert_eq!(
        finding(&m, "traefik.http.routers.app.rule").level,
        Level::Exact
    );
    assert_eq!(
        finding(&m, "--certificatesresolvers.le.acme.dnschallenge.provider").code,
        "traefik.static.credentials"
    );
    assert_eq!(
        finding(&m, "--certificatesresolvers.le.acme.storage").level,
        Level::Manual
    );
    assert!(finding(&m, "--api.insecure").security);
    assert_eq!(finding(&m, "TRAEFIK_LOG_LEVEL").level, Level::Approximate);
    assert_eq!(
        finding(&m, "services.traefik").code,
        "compose.service.traefik"
    );
    assert!(
        m.report
            .findings
            .iter()
            .any(|f| f.code == "output.labels_live"),
        "{:#?}",
        m.report.findings
    );
    assert!(!m.yaml.contains("routes:"), "{}", m.yaml);
}

