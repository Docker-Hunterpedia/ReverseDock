use super::*;

const COMPOSE: &str = r#"
services:
  whoami:
    image: traefik/whoami
    labels:
      - traefik.enable=true
      - traefik.http.routers.whoami.rule=Host(`whoami.example.com`)
      - traefik.http.routers.whoami.entrypoints=websecure
      - traefik.http.routers.whoami.tls.certresolver=le
      - traefik.http.routers.whoami.middlewares=strip
      - traefik.http.middlewares.strip.stripprefix.prefixes=/who
  api:
    image: example/api
    expose: ["8080", "9100"]
    labels:
      traefik.enable: "true"
      traefik.http.routers.api.rule: Host(`api.example.com`)
      traefik.http.services.api.loadbalancer.server.port: 8080
      traefik.http.middlewares.chain.chain.middlewares: a,b
  db:
    image: postgres
    labels:
      traefik.http.routers.db.rule: Host(`db.example.com`)
"#;

#[test]
fn compose_labels_become_routes_with_service_names_as_hosts() {
    let m = traefik(COMPOSE, false).unwrap();
    assert_eq!(m.input, Input::Compose);
    assert!(m.yaml.contains("whoami:"), "{}", m.yaml);
    assert!(m.yaml.contains("Host(`whoami.example.com`)"), "{}", m.yaml);
    // The service name is the backend's host; without a port, 80 is assumed and noted.
    assert!(m.yaml.contains("address: api:8080"), "{}", m.yaml);
    assert!(m.yaml.contains("address: whoami:80"), "{}", m.yaml);
    assert!(
        m.notes
            .iter()
            .any(|n| n.starts_with("whoami: no `expose`, `ports` or port label; assumed port 80")),
        "{:?}",
        m.notes
    );
    assert!(
        m.notes
            .iter()
            .any(|n| n.contains("chain.chain.middlewares") && n.contains("not in the supported")),
        "{:?}",
        m.notes
    );
    assert!(
        m.notes
            .iter()
            .any(|n| n.starts_with("db: has Traefik router labels but no `traefik.enable`")),
        "{:?}",
        m.notes
    );
    assert!(m.yaml.starts_with("# Generated by `rdock migrate traefik`"));
    // Defaults are left out.
    assert!(!m.yaml.contains("enabled: true"), "{}", m.yaml);
    assert!(!m.yaml.contains("priority: 0"), "{}", m.yaml);
}

#[test]
fn expose_by_default_follows_traefik() {
    let m = traefik(COMPOSE, true).unwrap();
    assert!(m.yaml.contains("Host(`db.example.com`)"), "{}", m.yaml);
}

#[test]
fn dynamic_configuration_keeps_every_server() {
    let dynamic = r"
http:
  routers:
    app:
      rule: Host(`app.example.com`)
      entryPoints: [web]
      service: app
      middlewares: [https]
      tls:
        domains:
          - main: example.com
            sans: ['*.example.com']
  services:
    app:
      loadBalancer:
        passHostHeader: false
        servers:
          - url: http://10.0.0.1:8080
          - url: http://10.0.0.2:8080/
  middlewares:
    https:
      redirectScheme: { scheme: https, permanent: true }
tcp:
  routers: {}
";
    let m = traefik(dynamic, false).unwrap();
    assert_eq!(m.input, Input::Dynamic);
    assert!(
        m.yaml.contains("10.0.0.1:8080") && m.yaml.contains("10.0.0.2:8080"),
        "{}",
        m.yaml
    );
    assert!(m.yaml.contains("pass_host_header: false"), "{}", m.yaml);
    assert!(m.yaml.contains("type: redirect"), "{}", m.yaml);
    assert!(
        m.yaml.contains("'*.example.com'") || m.yaml.contains("\"*.example.com\""),
        "{}",
        m.yaml
    );
    assert_eq!(m.notes.len(), 1, "{:?}", m.notes);
    assert!(m.notes[0].contains("planned for v0.6"));
}

#[test]
fn the_output_is_a_valid_configuration() {
    let m = traefik(COMPOSE, true).unwrap();
    let loaded = rdock_config::load_str(&m.yaml, rdock_config::Format::Yaml).unwrap();
    assert!(!loaded.has_errors(), "{:?}\n{}", loaded.diagnostics, m.yaml);
}

#[test]
fn other_documents_are_refused() {
    assert!(
        traefik("foo: 1\n", false)
            .unwrap_err()
            .contains("neither a Compose file")
    );
}
