//! What every migration writes the same way: pruning defaults out of generated objects, the
//! validation check of the result, the YAML under its comment header, and object names.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use rdock_model::{Config, Diagnostic};
use serde_json::{Map, Value};

use crate::report::{Finding, Level, Report};

/// A type's defaults as JSON, from the smallest valid input.
pub(crate) fn baseline<T: serde::de::DeserializeOwned + serde::Serialize>(
    minimal: &Value,
) -> Option<Value> {
    serde_json::from_value::<T>(minimal.clone())
        .ok()
        .and_then(|t| serde_json::to_value(t).ok())
}

/// Removes nulls, empty lists and maps, and fields equal to `base`.
pub(crate) fn prune(value: &mut Value, base: Option<&Value>) {
    let Value::Object(map) = value else { return };
    map.retain(|key, item| {
        let default = base.and_then(|b| b.get(key));
        if let Some(default) = default
            && item.is_object()
        {
            prune(item, Some(default));
        } else if item.is_object() {
            prune(item, None);
        }
        let empty = match item {
            Value::Null => true,
            Value::Array(a) => a.is_empty(),
            Value::Object(o) => o.is_empty(),
            _ => false,
        };
        // `tls: {}` on a listener means TLS with its defaults.
        let keep_empty =
            key == "tls" && item.as_object().is_some_and(Map::is_empty) && default.is_none();
        (keep_empty || !empty) && default != Some(item)
    });
}

/// Validation errors of the result on its own (references to other files are expected).
pub(crate) fn check(document: &Map<String, Value>) -> Vec<Finding> {
    let config: Config = match serde_json::from_value(Value::Object(document.clone())) {
        Ok(config) => config,
        Err(err) => {
            return vec![Finding::new(
                "output.invalid",
                format!("the result does not read as rdock.yaml: {err}"),
            )];
        }
    };
    config
        .validate()
        .into_iter()
        .filter(Diagnostic::is_error)
        .map(|d| {
            let target = d.path.clone();
            Finding::new("output.invalid", d.message).target(target)
        })
        .collect()
}

/// The YAML under a header: the counts, then every finding that is not exact.
pub(crate) fn render(
    tool: &str,
    document: &Map<String, Value>,
    report: &Report,
    full: bool,
) -> Result<String, String> {
    let body = if document.is_empty() {
        "{}\n".to_owned()
    } else {
        serde_saphyr::to_string(&Value::Object(document.clone())).map_err(|e| e.to_string())?
    };
    let what = if full {
        "a complete rdock.yaml"
    } else {
        "an rdock.yaml fragment (add listeners and defaults as needed)"
    };
    let mut header = format!(
        "# Generated by `{tool}` from {}: {what}. Review before use.\n# {}\n",
        report.source.files.join(", "),
        report.counts()
    );
    let notable: Vec<&Finding> = report.notable().collect();
    if notable.is_empty() {
        header.push_str("# Everything was migrated as it is.\n");
    } else {
        let _ = writeln!(header, "# To review ({}):", notable.len());
        for finding in notable {
            let line = finding.line().replace('\n', " ");
            let _ = writeln!(header, "#   - {line}");
        }
    }
    Ok(format!("{header}{body}"))
}

/// Findings collected for one item, reported as one finding at the worst level.
#[derive(Debug, Default, Clone)]
pub(crate) struct Notes {
    level: Option<Level>,
    parts: Vec<String>,
    hints: Vec<String>,
    security: bool,
}

impl Notes {
    pub(crate) fn note(&mut self, level: Level, message: impl Into<String>) {
        self.level = Some(self.level.map_or(level, |l| l.max(level)));
        let message = message.into();
        if !message.is_empty() && !self.parts.contains(&message) {
            self.parts.push(message);
        }
    }
    pub(crate) fn exact(&mut self, message: impl Into<String>) {
        self.note(Level::Exact, message);
    }
    pub(crate) fn approx(&mut self, message: impl Into<String>) {
        self.note(Level::Approximate, message);
    }
    pub(crate) fn manual(&mut self, message: impl Into<String>) {
        self.note(Level::Manual, message);
    }
    pub(crate) fn dropped(&mut self, message: impl Into<String>) {
        self.note(Level::Dropped, message);
    }
    pub(crate) fn hint(&mut self, hint: impl Into<String>) {
        let hint = hint.into();
        if !self.hints.contains(&hint) {
            self.hints.push(hint);
        }
    }
    pub(crate) fn security(&mut self) {
        self.security = true;
    }
    pub(crate) fn level(&self) -> Level {
        self.level.unwrap_or(Level::Exact)
    }
    pub(crate) fn is_manual(&self) -> bool {
        self.level() == Level::Manual
    }
    /// The finding, with the code `<family>.<level>` (`dropped` is `unsupported`).
    pub(crate) fn finding(&self, family: &str, target: Option<&str>) -> Finding {
        let suffix = match self.level() {
            Level::Exact => "exact",
            Level::Approximate => "approximate",
            Level::Manual => "manual",
            Level::Dropped => "unsupported",
        };
        let message = if self.parts.is_empty() {
            "translated".to_owned()
        } else {
            self.parts.join("; ")
        };
        let mut finding = Finding::new(&format!("{family}.{suffix}"), message);
        if let Some(target) = target {
            finding = finding.target(target);
        }
        if !self.hints.is_empty() {
            finding = finding.hint(self.hints.join("; "));
        }
        if self.security {
            finding = finding.security();
        }
        finding
    }
}

/// Generated objects of one kind, de-duplicated by content.
#[derive(Debug, Default)]
pub(crate) struct Objects {
    pub(crate) map: Map<String, Value>,
    names: Names,
}

impl Objects {
    /// Adds `value` under a name built from `parts`, or returns the name of an equal object.
    pub(crate) fn add(&mut self, parts: &[&str], value: Value) -> String {
        if let Some((name, _)) = self.map.iter().find(|(_, v)| **v == value) {
            return name.clone();
        }
        let name = self.names.unique(parts);
        self.map.insert(name.clone(), value);
        name
    }
}

impl Notes {
    /// Whether no message was noted.
    pub(crate) fn parts_empty(&self) -> bool {
        self.parts.is_empty()
    }

    /// One manual message as a finding of `family`.
    pub(crate) fn manual_finding(family: &str, message: &str) -> Finding {
        let mut notes = Self::default();
        notes.manual(message);
        notes.finding(family, None)
    }

    /// The finding with another code (whose level must be the notes' level).
    pub(crate) fn finding_as(&self, code: &str, target: Option<&str>) -> Finding {
        let mut finding = self.finding("x", target);
        code.clone_into(&mut finding.code);
        if let Some(info) = crate::report::code_info(code) {
            finding.level = info.level;
        }
        finding
    }
}

/// Unique object names: `app-example-com`, then `app-example-com-2`, …
#[derive(Debug, Default)]
pub(crate) struct Names {
    taken: BTreeSet<String>,
}

impl Names {
    /// A name built from `parts` (lower-cased, anything but letters and digits as `-`), unique
    /// among the names handed out so far.
    pub(crate) fn unique(&mut self, parts: &[&str]) -> String {
        let mut base = parts
            .iter()
            .map(|p| slug(p))
            .filter(|p| !p.is_empty())
            .collect::<Vec<_>>()
            .join("-");
        if base.is_empty() {
            "default".clone_into(&mut base);
        }
        if base.len() > 60 {
            base.truncate(60);
            base = base.trim_end_matches('-').to_owned();
        }
        let mut name = base.clone();
        let mut n = 2;
        while self.taken.contains(&name) {
            name = format!("{base}-{n}");
            n += 1;
        }
        self.taken.insert(name.clone());
        name
    }
}

/// `App.Example.com/api` → `app-example-com-api`.
pub(crate) fn slug(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
        } else if !out.ends_with('-') {
            out.push('-');
        }
    }
    out.trim_matches('-').to_owned()
}

/// A regular expression that matches `text` literally.
pub(crate) fn escape(text: &str) -> String {
    regex::escape(text)
}

/// `text` as a regex replacement that inserts it literally (`$` doubled).
pub(crate) fn literal_replacement(text: &str) -> String {
    text.replace('$', "$$")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_are_unique_slugs() {
        let mut names = Names::default();
        assert_eq!(
            names.unique(&["App.Example.com", "/api/"]),
            "app-example-com-api"
        );
        assert_eq!(
            names.unique(&["app.example.com", "api"]),
            "app-example-com-api-2"
        );
        assert_eq!(names.unique(&[""]), "default");
    }

    #[test]
    fn replacements_keep_dollars_literal() {
        assert_eq!(literal_replacement("/a$1"), "/a$$1");
    }
}
