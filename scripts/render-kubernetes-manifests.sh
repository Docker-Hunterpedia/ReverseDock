#!/usr/bin/env bash
# Renders the Helm chart with default values into deploy/kubernetes/install.yaml.
#   scripts/render-kubernetes-manifests.sh          write the file
#   scripts/render-kubernetes-manifests.sh --check  exit 1 when the committed file is stale (CI)
# Needs helm (3 or 4) on PATH, or HELM=/path/to/helm.
set -euo pipefail
cd "$(dirname "$0")/.."

HELM="${HELM:-helm}"
OUT="deploy/kubernetes/install.yaml"
NAMESPACE="reversedock-system"

mode="write"
case "${1:-}" in
  "") ;;
  --check) mode="check" ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
  echo "# Generated by scripts/render-kubernetes-manifests.sh from deploy/helm/reversedock; do not edit."
  echo "# helm template reversedock deploy/helm/reversedock --namespace ${NAMESPACE}"
  echo "# Needs the Gateway API CRDs (v1.7.0, Standard channel) installed first: see deploy/kubernetes/README.md."
  "$HELM" template reversedock deploy/helm/reversedock --namespace "$NAMESPACE"
} > "$tmp"

if [ "$mode" = "check" ]; then
  if ! diff -u "$OUT" "$tmp"; then
    echo "$OUT is stale; run scripts/render-kubernetes-manifests.sh and commit the result" >&2
    exit 1
  fi
  echo "$OUT is up to date"
else
  cp "$tmp" "$OUT"
  echo "rendered $OUT"
fi
